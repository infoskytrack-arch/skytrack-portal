function findStopIndex(stops: string[], targetCode: string): { idx: number; exact: boolean } {
  const exactIdx = stops.indexOf(targetCode);
  if (exactIdx !== -1) {
    return { idx: exactIdx, exact: true };
  }
  const targetGroup = getHubGroup(targetCode);
  if (targetGroup !== targetCode) {
    const hubIdx = stops.findIndex((s) => getHubGroup(s) === targetGroup);
    if (hubIdx !== -1) {
      return { idx: hubIdx, exact: false };
    }
  }
  return { idx: -1, exact: false };
}

export function findTrainsForRoute(
  from: Station,
  to: Station,
  selectedClass: TravelClassCode
): TrainSchedule[] {
  const distanceKm = calculateRailwayDistanceKm(from, to);
  const scoredMatches: Array<{ train: TrainSchedule; score: number }> = [];

  for (const train of TRAIN_SCHEDULES) {
    if (
      selectedClass !== 'ALL' &&
      !train.classes.includes(selectedClass as SelectableClassCode)
    ) {
      continue;
    }

    const stops =
      train.routeStops && train.routeStops.length >= 2
        ? train.routeStops
        : [train.fromCode, train.toCode];

    const fromHit = findStopIndex(stops, from.code);
    const toHit = findStopIndex(stops, to.code);

    if (fromHit.idx !== -1 && toHit.idx !== -1 && fromHit.idx < toHit.idx) {
      let score = 0;
      if (train.fromCode === from.code && train.toCode === to.code) {
        score += 100;
      } else if (fromHit.exact && toHit.exact) {
        score += 80;
      } else if (fromHit.exact || toHit.exact) {
        score += 55;
      } else {
        score += 35;
      }

      const isPassingIntermediate =
        (fromHit.exact && from.code !== train.fromCode) ||
        (toHit.exact && to.code !== train.toCode);

      scoredMatches.push({
        train: {
          ...train,
          distanceKm,
          matchedNote: isPassingIntermediate
            ? `Stops at ${from.code} → ${to.code} (Full route: ${train.fromCode}–${train.toCode})`
            : undefined,
        },
        score,
      });
      continue;
    }

    // Smart West Bengal feeder support (e.g., Barddhaman BWN / Memari MYM searching long-distance routes)
    if (WB_HOWRAH_FEEDERS.has(from.code) && KOLKATA_HUBS.has(train.fromCode)) {
      if (toHit.idx !== -1) {
        scoredMatches.push({
          train: {
            ...train,
            distanceKm,
            matchedNote: `Boards from nearby hub ${train.fromName} (${train.fromCode})`,
          },
          score: 20,
        });
      }
    } else if (WB_HOWRAH_FEEDERS.has(to.code) && KOLKATA_HUBS.has(train.toCode)) {
      if (fromHit.idx !== -1) {
        scoredMatches.push({
          train: {
            ...train,
            distanceKm,
            matchedNote: `Arrives at nearby hub ${train.toName} (${train.toCode})`,
          },
          score: 20,
        });
      }
    }
  }

  // Deduplicate by trainNumber keeping highest score
  const seen = new Set<string>();
  scoredMatches.sort((a, b) => b.score - a.score);
  const uniqueMatches: TrainSchedule[] = [];
  for (const item of scoredMatches) {
    if (!seen.has(item.train.trainNumber)) {
      seen.add(item.train.trainNumber);
      uniqueMatches.push(item.train);
    }
  }

  // Ensure ANY Indian Railways route across all 185+ stations shows at least 3 realistic trains
  if (uniqueMatches.length < 3) {
    const simulated = generateAllIndiaRouteTrains(
      from,
      to,
      distanceKm,
      seen,
      3 - uniqueMatches.length
    ).filter(
      (tr) =>
        selectedClass === 'ALL' ||
        tr.classes.includes(selectedClass as SelectableClassCode)
    );
    uniqueMatches.push(...simulated);
  }

  return [...uniqueMatches, buildCustomRouteTrain(from, to, distanceKm, uniqueMatches.length > 0)];
}
