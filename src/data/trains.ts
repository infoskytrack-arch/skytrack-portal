function getHubGroup(code: string): string {
  if (KOLKATA_HUBS.has(code)) return 'KOLKATA_GROUP';
  if (MUMBAI_HUBS.has(code)) return 'MUMBAI_GROUP';
  if (DELHI_HUBS.has(code)) return 'DELHI_GROUP';
  if (BENGALURU_HUBS.has(code)) return 'BENGALURU_GROUP';
  if (CHENNAI_HUBS.has(code)) return 'CHENNAI_GROUP';
  if (PATNA_HUBS.has(code)) return 'PATNA_GROUP';
  if (HYDERABAD_HUBS.has(code)) return 'HYDERABAD_GROUP';
  if (GUWAHATI_HUBS.has(code)) return 'GUWAHATI_GROUP';
  return code;
}

